// main.js = src/core.js + src/setup.js, pasted together. No bundler: the host evaluates main.js as a
// plain setup body (`new Function('ctx', code)`), so neither file may use import / export.
// Run: node build.mjs (main.js is committed; rebuild after editing src/).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const dir = path.dirname(fileURLToPath(import.meta.url))
const read = (f) => readFileSync(path.join(dir, f), 'utf8')
const { version } = JSON.parse(read('manifest.json'))
const out = `// Inline completion ${version} — generated by build.mjs from src/core.js + src/setup.js. Do not edit.\n`
  + read('src/core.js') + '\n' + read('src/setup.js')
writeFileSync(path.join(dir, 'main.js'), out)
console.log(`main.js written (${out.length} chars)`)
